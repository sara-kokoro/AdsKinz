"""Kurigram client lifecycle for read-only Telegram message view polling.

IMPORTANT: ``MTPROTO_SESSION_STRING`` is generated ONCE manually by an operator
on a local machine and is NEVER regenerated by deployed code. If it is missing
or invalid, this module logs a warning and disables the watcher; it never starts
an interactive login flow or requests a phone number/code.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any

from app.config import settings

# Kurigram installs under the ``pyrogram`` import name. Do not replace this with
# the original Pyrogram package: it is unmaintained and must never be used here.
try:  # pragma: no cover - depends on optional runtime package installation
    from pyrogram import Client
    from pyrogram.errors import FloodWait
except ImportError:  # pragma: no cover - lets the API import without MTProto extras
    Client = None  # type: ignore[assignment,misc]

    class FloodWait(Exception):
        """Fallback used only when Kurigram is not installed."""

        value = 0


logger = logging.getLogger(__name__)

_client: Any | None = None
_started = False
_disabled_reason: str | None = None
_start_task: asyncio.Task[Any | None] | None = None

# Kurigram's ``client.start()`` has no built-in timeout: a slow or unreachable
# Telegram DC would hang forever. Bound it so startup and jobs can never stall.
START_TIMEOUT_SECONDS = 30


def is_configured() -> bool:
    """Whether the non-interactive Kurigram credentials and package are available."""
    return bool(
        Client is not None
        and settings.MTPROTO_API_ID
        and settings.MTPROTO_API_HASH
        and settings.MTPROTO_SESSION_STRING
    )


async def get_client() -> Any | None:
    """Lazily build the in-memory Kurigram client without initiating a login."""
    global _client, _disabled_reason
    if _disabled_reason is not None:
        return None
    if not is_configured():
        _disabled_reason = "missing credentials or Kurigram package"
        logger.warning("mtproto.disabled reason=%s", _disabled_reason)
        return None
    if _client is None:
        _client = Client(  # type: ignore[misc,operator]
            name="adskinz_views_watcher",
            api_id=settings.MTPROTO_API_ID,
            api_hash=settings.MTPROTO_API_HASH,
            session_string=settings.MTPROTO_SESSION_STRING,
            in_memory=True,
            no_updates=True,
        )
    return _client


async def start_client() -> Any | None:
    """Start the configured session without ever attempting interactive authorization."""
    global _started, _disabled_reason
    if not settings.ENABLE_MTPROTO:
        return None
    client = await get_client()
    if client is None:
        return None
    if _started:
        return client
    try:
        await asyncio.wait_for(client.start(), timeout=START_TIMEOUT_SECONDS)
    except Exception as exc:  # noqa: BLE001 - invalid sessions must disable, not prompt
        _disabled_reason = f"session start failed: {exc!r}"
        logger.warning("mtproto.disabled reason=%s", _disabled_reason)
        _started = False
        return None
    _started = True
    logger.info("mtproto.started")
    return client


async def start_client_background() -> None:
    """Start the Kurigram session in a background task so startup never blocks.

    ``client.start()`` performs a network handshake with Telegram that can hang;
    awaiting it from the FastAPI lifespan would prevent the HTTP server from
    ever answering (e.g. the Koyeb health check). The views watcher still calls
    ``start_client()`` directly and simply skips its run until the session is up.
    """
    global _start_task
    if not settings.ENABLE_MTPROTO or not is_configured():
        return
    if _start_task is not None and not _start_task.done():
        return
    _start_task = asyncio.create_task(start_client(), name="adskinz-mtproto-start")


async def mtproto_status() -> dict:
    """Whether the read-only MTProto session used for view-count billing is
    actually connected, and why it isn't if not. This client is what turns
    real Telegram views into billed impressions (app/mtproto/views_watcher.py)
    — if it's disabled, posts keep accumulating real views on Telegram with
    $0 ever charged or credited, silently, since the polling job just
    no-ops every cycle instead of raising."""
    return {
        "configured": is_configured(),
        "enable_mtproto_setting": settings.ENABLE_MTPROTO,
        "started": _started,
        "disabled_reason": _disabled_reason,
    }


async def stop_client() -> None:
    """Cancel any pending start, then disconnect the shared Kurigram client."""
    global _started, _start_task
    if _start_task is not None:
        _start_task.cancel()
        try:
            await _start_task
        except asyncio.CancelledError:
            pass
        _start_task = None
    if _client is not None and _started:
        try:
            await _client.stop()
        except Exception as exc:  # noqa: BLE001 - shutdown must remain best effort
            logger.warning("mtproto.stop_failed error=%s", exc)
        finally:
            _started = False
    logger.info("mtproto.stopped")
